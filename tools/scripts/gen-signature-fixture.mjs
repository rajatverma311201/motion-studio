#!/usr/bin/env node
/**
 * Regenerate the ECDSA signature fixture used by the signing chapter.
 *
 *   pnpm gen:signature-fixture
 *
 * Creates a fresh P-256 key pair, signs `pay 500 to Bob` in the IEEE P1363
 * format and writes only the public JWK and the 64-byte signature. The private
 * key exists in memory for the duration of this script and is never written.
 */
import {generateKeyPairSync, sign} from 'node:crypto';
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT_FILE = path.join(ROOT, 'packages/video-kit/src/crypto-demo/signature-fixture.ts');
const MESSAGE = 'pay 500 to Bob';

const {privateKey, publicKey} = generateKeyPairSync('ec', {namedCurve: 'P-256'});
const signature = sign('sha256', MESSAGE, {
  key: privateKey,
  dsaEncoding: 'ieee-p1363',
});
const jwk = publicKey.export({format: 'jwk'});

if (typeof jwk.x !== 'string' || typeof jwk.y !== 'string') {
  throw new Error('Expected an EC public JWK with x and y coordinates.');
}

const signatureHex = signature.toString('hex');
if (signatureHex.length !== 128) {
  throw new Error(`Expected a 64-byte P1363 signature, got ${signature.length} bytes.`);
}

const quote = value => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const source = `/**
 * Generated by \`pnpm gen:signature-fixture\`. Do not edit by hand.
 *
 * A P-256 key pair signed "pay 500 to Bob" with ECDSA. Only the public JWK and
 * the signature are stored here; the private key was discarded by the generator.
 */

/** The public JWK for the demo signing key. */
export const DEMO_PUBLIC_JWK = {
  kty: 'EC',
  crv: 'P-256',
  x: ${quote(jwk.x)},
  y: ${quote(jwk.y)},
} as const;

/** ECDSA P-256 signature over the demo message, 64 bytes in 128 hex characters. */
export const DEMO_SIGNATURE_HEX =
  '${signatureHex}';
`;

await writeFile(OUT_FILE, source, 'utf8');
console.log(`wrote ${path.relative(ROOT, OUT_FILE)}`);
