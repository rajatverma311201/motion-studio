#!/usr/bin/env node
/**
 * Regenerate the ES256 fixture used by the JWKS chapter.
 *
 *   pnpm gen:jwt-fixtures
 *
 * Creates a fresh P-256 key pair, signs the same payload as the HS256 fixture and
 * writes only the public JWK and the token. The private key exists in memory for
 * the duration of this script and is never written anywhere.
 */
import {generateKeyPairSync, sign} from 'node:crypto';
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {encodeBase64Url} from '../../packages/video-kit/src/jwt/base64url.ts';
import {JWT_PAYLOAD_JSON} from '../../packages/video-kit/src/jwt/jwt-fixtures.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT_FILE = path.join(ROOT, 'packages/video-kit/src/jwt/jwt-es256-fixture.ts');
const HEADER_JSON = '{"alg":"ES256","typ":"JWT","kid":"key-1"}';

const {privateKey, publicKey} = generateKeyPairSync('ec', {namedCurve: 'P-256'});
const header = encodeBase64Url(HEADER_JSON);
const payload = encodeBase64Url(JWT_PAYLOAD_JSON);
const signingInput = `${header}.${payload}`;
const signature = sign('sha256', signingInput, {
  key: privateKey,
  dsaEncoding: 'ieee-p1363',
}).toString('base64url');
const jwk = publicKey.export({format: 'jwk'});

if (typeof jwk.x !== 'string' || typeof jwk.y !== 'string') {
  throw new Error('Expected an EC public JWK with x and y coordinates.');
}

const source = `/**
 * Generated by \`pnpm gen:jwt-fixtures\`. Do not edit by hand.
 *
 * A P-256 key pair signed the same payload as the HS256 fixture. Only the public
 * JWK is stored here; the private key was discarded by the generator.
 */

/** ES256 header JSON: algorithm, type and the key id used by the JWKS document. */
export const ES256_HEADER_JSON = ${JSON.stringify(HEADER_JSON)};

/** Base64URL of {@link ES256_HEADER_JSON}. */
export const ES256_HEADER = ${JSON.stringify(header)};

/** Base64URL of the shared payload JSON. */
export const ES256_PAYLOAD = ${JSON.stringify(payload)};

/** Base64URL signature over \`header.payload\`, in the JWS P-1363 format. */
export const ES256_SIGNATURE = ${JSON.stringify(signature)};

/** A valid ES256 token for the keys chapter. */
export const ES256_TOKEN = \`\${ES256_HEADER}.\${ES256_PAYLOAD}.\${ES256_SIGNATURE}\`;

/** The public JWK as published in a JWKS document. */
export const ES256_JWK = {
  kty: 'EC',
  crv: 'P-256',
  x: ${JSON.stringify(jwk.x)},
  y: ${JSON.stringify(jwk.y)},
  kid: 'key-1',
  use: 'sig',
  alg: 'ES256',
} as const;
`;

await writeFile(OUT_FILE, source, 'utf8');
console.log(`wrote ${path.relative(ROOT, OUT_FILE)}`);
