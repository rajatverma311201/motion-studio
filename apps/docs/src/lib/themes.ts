import themesData from '@/generated/themes.json';

export type ThemeMode = 'dark' | 'light';
export type ElevationStyle = 'hard' | 'soft' | 'glow' | 'none';
export type CaptionStyle = 'bar' | 'tonal' | 'outline';
export type TitleStyle = 'slab' | 'plain' | 'pill';

export interface ThemeFonts {
  sans: string;
  mono: string;
  display: string;
}

export interface ThemeShape {
  radiusScale: number;
  borderWidthScale: number;
  elevation: ElevationStyle;
}

export interface ThemeHud {
  captionStyle: CaptionStyle;
  titleStyle: TitleStyle;
  gridVisible: boolean;
}

export interface ThemeVariant {
  colors: Record<string, string>;
  shape: ThemeShape;
  hud: ThemeHud;
}

export interface ThemeEntry {
  id: string;
  name: string;
  family: string;
  description: string;
  defaultMode: ThemeMode;
  fonts: ThemeFonts;
  variants: Record<ThemeMode, ThemeVariant>;
}

export interface ThemesJson {
  defaultThemeId: string;
  themes: ThemeEntry[];
}

/** Generated by `tools/scripts/sync-themes.mjs`; never imported from video-kit directly. */
export const themesJson = themesData as ThemesJson;
